package ru.validum.core.common;

/**
 * Организационно-правовая форма ЮЛ.
 *
 * <p>{@code prefix} — префикс в наименовании («ООО», «АО», «ПАО», «НКО», «Фонд», «ГУП», «МУП»).
 *
 * <p>{@code okopf} — код по ОК 028-2012.
 *
 * <p>{@code okfs} — код формы собственности по ОК 027-99:
 *
 * <ul>
 *   <li>13 — муниципальная;
 *   <li>14 — собственность субъектов РФ;
 *   <li>16 — частная.
 * </ul>
 *
 * <p>{@code budget} — бюджетный статус организации: «Небюджетная», «Некоммерческая», «Бюджетная».
 *
 * <p><b>ОПФ «ИП» здесь нет.</b> Индивидуальный предприниматель — это отдельная сущность
 * ({@code IpProfile}, композиция над ФЛ с ОГРНИП и отчеством «ИП Автотеста»). Добавлять ИП в
 * {@code OrganizationType} значило бы создать два разных способа сгенерировать одного и того же
 * субъекта.
 */
public enum OrganizationType {

  /** Общество с ограниченной ответственностью. */
  LLC("ООО", "65", "16", "Небюджетная организация"),

  /** Непубличное акционерное общество. */
  JSC("АО", "47", "16", "Небюджетная организация"),

  /** Публичное акционерное общество. */
  PJSC("ПАО", "47", "16", "Небюджетная организация"),

  /** Некоммерческая организация (АНО, ассоциация, союз). */
  NCO("НКО", "85", "16", "Некоммерческая организация"),

  /** Фонд (благотворительный, пенсионный, общественный). */
  FOUNDATION("Фонд", "88", "16", "Некоммерческая организация"),

  /** Государственное унитарное предприятие (собственность субъекта РФ). */
  SE("ГУП", "61", "14", "Бюджетная организация"),

  /** Муниципальное унитарное предприятие (муниципальная собственность). */
  ME("МУП", "62", "13", "Бюджетная организация");

  private final String prefix;
  private final String okopf;
  private final String okfs;
  private final String budget;

  OrganizationType(String prefix, String okopf, String okfs, String budget) {
    this.prefix = prefix;
    this.okopf = okopf;
    this.okfs = okfs;
    this.budget = budget;
  }

  public String prefix() {
    return prefix;
  }

  public String okopf() {
    return okopf;
  }

  public String okfs() {
    return okfs;
  }

  public String budget() {
    return budget;
  }
}
