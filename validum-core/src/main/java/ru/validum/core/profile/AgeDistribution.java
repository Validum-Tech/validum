package ru.validum.core.profile;

/**
 * Как выбирается возраст профиля, когда задан диапазон {@code --age-range}.
 *
 * <p>Без диапазона возраст фиксирован ({@code --age} или каскадный дефолт), поэтому
 * распределение не применяется. Распределение влияет только на то, какое число попадёт
 * в профиль; порядок обращений к {@link java.util.Random} детерминирован, значит один и тот
 * же seed при одном распределении даёт один и тот же набор.
 */
public enum AgeDistribution {

  /** Равномерно по всему диапазону: каждая граница встречается одинаково часто. */
  UNIFORM,

  /**
   * По демографическим когортам: трудоспособных больше, детей и пенсионеров меньше.
   *
   * <p>Веса (в процентах): 0–6 — 6, 7–13 — 7, 14–17 — 5, 18–24 — 10, 25–34 — 18,
   * 35–44 — 17, 45–54 — 14, 55–64 — 13, 65–79 — 8, 80+ — 2. Если когорта целиком
   * вне диапазона, возраст берётся равномерно.
   */
  REALISTIC
}
