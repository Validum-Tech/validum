package ru.validum.core.profile;

/**
 * Поле профиля, которое можно намеренно испортить — контрольная сумма становится неверной.
 *
 * <p>Используется в негативных сценариях: сам профиль остаётся согласованным по остальным полям,
 * но АБС должна отвергнуть его из-за одного битого поля.
 */
public enum CorruptField {
  /** Контрольные разряды ИНН не сходятся. */
  INN,

  /** Контрольное число СНИЛС не сходится. */
  SNILS
}
